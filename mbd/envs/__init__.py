from ..robots.tt2d import TractorTrailer2d
from ..robots.acc_tt2d import AccTractorTrailer2d
from ..robots.kinematic_bicycle2d import KinematicBicycle2d
from ..robots.n_trailer2d import NTrailer2d

def get_env(
    env_name: str,
    case: str = "navigation",
    env_config=None,
    dt=0.2,
    H=50,
    motion_preference=0,
    collision_penalty=0.15,
    hitch_penalty=0.10,
    enable_shielded_rollout_collision=True,
    enable_shielded_rollout_hitch=True,
    enable_projection=False,
    enable_guidance=False,
    reward_threshold=25.0,
    ref_reward_threshold=5.0,
    max_w_theta=0.75,
    hitch_angle_weight=0.2,
    l1=3.23,
    l2=2.9,
    lh=1.15,
    lf1=0.9,
    lr=1.848,
    lf2=1.42,
    lr2=3.225,
    tractor_width=2.0,
    trailer_width=2.5,
    v_max=3.0,
    delta_max_deg=55.0,
    d_thr_factor=1.0,
    k_switch=2.5,
    steering_weight=0.05,
    preference_penalty_weight=0.05,
    heading_reward_weight=0.5,
    terminal_reward_threshold=10.0,
    terminal_reward_weight=1.0,
    ref_pos_weight=0.3,
    ref_theta1_weight=0.5,
    ref_theta2_weight=0.2,
    a_max=2.0,
    omega_max=1.0,
    num_trailers: int = 1,
    perturbation_level: int = 0,
    perturbation_seed: int | None = None,
    control_noise_std=(0.05, 0.05),
    param_uncertainty_std: float = 0.10,
    non_gaussian_dist: str = "student_t",
    non_gaussian_df: float = 2.5,
    state_disturbance_scale: float = 0.05,
    disturbance_clip_factor: float = 5.0,
    perturbed_l1: float | None = None,
    perturbed_l2: float | None = None,
    perturbed_lh: float | None = None,
    enable_robust_shielding: bool = False,
    tube_obstacle_margin=0.0,
    tube_hitch_margin=0.0,
    enable_ilqr_backup: bool = False,
    ilqr_iters: int = 4,
):
    perturbation_kwargs = dict(
        perturbation_level=perturbation_level,
        perturbation_seed=perturbation_seed,
        control_noise_std=control_noise_std,
        param_uncertainty_std=param_uncertainty_std,
        non_gaussian_dist=non_gaussian_dist,
        non_gaussian_df=non_gaussian_df,
        state_disturbance_scale=state_disturbance_scale,
        disturbance_clip_factor=disturbance_clip_factor,
        perturbed_l1=perturbed_l1,
        perturbed_l2=perturbed_l2,
        perturbed_lh=perturbed_lh,
    )
    robust_kwargs = dict(
        enable_robust_shielding=enable_robust_shielding,
        tube_obstacle_margin=tube_obstacle_margin,
        tube_hitch_margin=tube_hitch_margin,
        enable_ilqr_backup=enable_ilqr_backup,
        ilqr_iters=ilqr_iters,
    )
    if env_name == "tt2d":
        if num_trailers == 0:
            return KinematicBicycle2d(
                case=case,
                env_config=env_config,
                dt=dt,
                H=H,
                motion_preference=motion_preference,
                collision_penalty=collision_penalty,
                hitch_penalty=hitch_penalty,  # ignored by bicycle
                enable_shielded_rollout_collision=enable_shielded_rollout_collision,
                enable_shielded_rollout_hitch=enable_shielded_rollout_hitch,
                enable_projection=enable_projection,
                enable_guidance=enable_guidance,
                reward_threshold=reward_threshold,
                ref_reward_threshold=ref_reward_threshold,
                max_w_theta=max_w_theta,
                hitch_angle_weight=hitch_angle_weight,  # ignored by bicycle
                l1=l1,
                l2=l2,
                lh=lh,
                lf1=lf1,
                lr=lr,
                lf2=lf2,
                lr2=lr2,
                tractor_width=tractor_width,
                trailer_width=trailer_width,
                v_max=v_max,
                delta_max_deg=delta_max_deg,
                d_thr_factor=d_thr_factor,
                k_switch=k_switch,
                steering_weight=steering_weight,
                preference_penalty_weight=preference_penalty_weight,
                heading_reward_weight=heading_reward_weight,
                terminal_reward_threshold=terminal_reward_threshold,
                terminal_reward_weight=terminal_reward_weight,
                ref_pos_weight=ref_pos_weight,
                ref_theta1_weight=ref_theta1_weight,
                ref_theta2_weight=ref_theta2_weight,
                **perturbation_kwargs,
            )
        if num_trailers >= 2:
            return NTrailer2d(
                num_trailers=num_trailers,
                case=case,
                env_config=env_config,
                dt=dt,
                H=H,
                motion_preference=motion_preference,
                collision_penalty=collision_penalty,
                hitch_penalty=hitch_penalty,
                enable_shielded_rollout_collision=enable_shielded_rollout_collision,
                enable_shielded_rollout_hitch=enable_shielded_rollout_hitch,
                enable_projection=enable_projection,
                enable_guidance=enable_guidance,
                reward_threshold=reward_threshold,
                ref_reward_threshold=ref_reward_threshold,
                max_w_theta=max_w_theta,
                hitch_angle_weight=hitch_angle_weight,
                l1=l1,
                l2=l2,
                lh=lh,
                lf1=lf1,
                lr=lr,
                lf2=lf2,
                lr2=lr2,
                tractor_width=tractor_width,
                trailer_width=trailer_width,
                v_max=v_max,
                delta_max_deg=delta_max_deg,
                d_thr_factor=d_thr_factor,
                k_switch=k_switch,
                steering_weight=steering_weight,
                preference_penalty_weight=preference_penalty_weight,
                heading_reward_weight=heading_reward_weight,
                terminal_reward_threshold=terminal_reward_threshold,
                terminal_reward_weight=terminal_reward_weight,
                ref_pos_weight=ref_pos_weight,
                ref_theta1_weight=ref_theta1_weight,
                ref_theta2_weight=ref_theta2_weight,
                **perturbation_kwargs,
            )
        # default single-trailer
        return TractorTrailer2d(
            case=case,
            env_config=env_config,
            dt=dt,
            H=H,
            motion_preference=motion_preference,
            collision_penalty=collision_penalty,
            hitch_penalty=hitch_penalty,
            enable_shielded_rollout_collision=enable_shielded_rollout_collision,
            enable_shielded_rollout_hitch=enable_shielded_rollout_hitch,
            enable_projection=enable_projection,
            enable_guidance=enable_guidance,
            reward_threshold=reward_threshold,
            ref_reward_threshold=ref_reward_threshold,
            max_w_theta=max_w_theta,
            hitch_angle_weight=hitch_angle_weight,
            l1=l1,
            l2=l2,
            lh=lh,
            lf1=lf1,
            lr=lr,
            lf2=lf2,
            lr2=lr2,
            tractor_width=tractor_width,
            trailer_width=trailer_width,
            v_max=v_max,
            delta_max_deg=delta_max_deg,
            d_thr_factor=d_thr_factor,
            k_switch=k_switch,
            steering_weight=steering_weight,
            preference_penalty_weight=preference_penalty_weight,
            heading_reward_weight=heading_reward_weight,
            terminal_reward_threshold=terminal_reward_threshold,
            terminal_reward_weight=terminal_reward_weight,
            ref_pos_weight=ref_pos_weight,
            ref_theta1_weight=ref_theta1_weight,
            ref_theta2_weight=ref_theta2_weight,
            **perturbation_kwargs,
            **robust_kwargs,
        )
    elif env_name == "n_trailer2d":
        return NTrailer2d(
            num_trailers=num_trailers,
            case=case,
            env_config=env_config,
            dt=dt,
            H=H,
            motion_preference=motion_preference,
            collision_penalty=collision_penalty,
            hitch_penalty=hitch_penalty,
            enable_shielded_rollout_collision=enable_shielded_rollout_collision,
            enable_shielded_rollout_hitch=enable_shielded_rollout_hitch,
            enable_projection=enable_projection,
            enable_guidance=enable_guidance,
            reward_threshold=reward_threshold,
            ref_reward_threshold=ref_reward_threshold,
            max_w_theta=max_w_theta,
            hitch_angle_weight=hitch_angle_weight,
            l1=l1,
            l2=l2,
            lh=lh,
            lf1=lf1,
            lr=lr,
            lf2=lf2,
            lr2=lr2,
            tractor_width=tractor_width,
            trailer_width=trailer_width,
            v_max=v_max,
            delta_max_deg=delta_max_deg,
            d_thr_factor=d_thr_factor,
            k_switch=k_switch,
            steering_weight=steering_weight,
            preference_penalty_weight=preference_penalty_weight,
            heading_reward_weight=heading_reward_weight,
            terminal_reward_threshold=terminal_reward_threshold,
            terminal_reward_weight=terminal_reward_weight,
            ref_pos_weight=ref_pos_weight,
            ref_theta1_weight=ref_theta1_weight,
            ref_theta2_weight=ref_theta2_weight,
            **perturbation_kwargs,
        )
    elif env_name == "acc_tt2d":
        return AccTractorTrailer2d(
            case=case,
            env_config=env_config,
            dt=dt,
            H=H,
            motion_preference=motion_preference,
            collision_penalty=collision_penalty,
            hitch_penalty=hitch_penalty,
            enable_shielded_rollout_collision=enable_shielded_rollout_collision,
            enable_shielded_rollout_hitch=enable_shielded_rollout_hitch,
            enable_projection=enable_projection,
            enable_guidance=enable_guidance,
            reward_threshold=reward_threshold,
            ref_reward_threshold=ref_reward_threshold,
            max_w_theta=max_w_theta,
            hitch_angle_weight=hitch_angle_weight,
            l1=l1,
            l2=l2,
            lh=lh,
            lf1=lf1,
            lr=lr,
            lf2=lf2,
            lr2=lr2,
            tractor_width=tractor_width,
            trailer_width=trailer_width,
            v_max=v_max,
            delta_max_deg=delta_max_deg,
            d_thr_factor=d_thr_factor,
            k_switch=k_switch,
            steering_weight=steering_weight,
            preference_penalty_weight=preference_penalty_weight,
            heading_reward_weight=heading_reward_weight,
            terminal_reward_threshold=terminal_reward_threshold,
            terminal_reward_weight=terminal_reward_weight,
            ref_pos_weight=ref_pos_weight,
            ref_theta1_weight=ref_theta1_weight,
            ref_theta2_weight=ref_theta2_weight,
            a_max=a_max,
            omega_max=omega_max,
            **perturbation_kwargs,
            **robust_kwargs,
        )
    elif env_name == "kinematic_bicycle2d":
        return KinematicBicycle2d(
            case=case,
            env_config=env_config,
            dt=dt,
            H=H,
            motion_preference=motion_preference,
            collision_penalty=collision_penalty,
            hitch_penalty=hitch_penalty,  # Will be ignored by bicycle model
            enable_shielded_rollout_collision=enable_shielded_rollout_collision,
            enable_shielded_rollout_hitch=enable_shielded_rollout_hitch,  # Will be ignored by bicycle model
            enable_projection=enable_projection,
            enable_guidance=enable_guidance,
            reward_threshold=reward_threshold,
            ref_reward_threshold=ref_reward_threshold,
            max_w_theta=max_w_theta,
            hitch_angle_weight=hitch_angle_weight,  # Will be ignored by bicycle model
            l1=l1,
            l2=l2,  # Will be ignored by bicycle model
            lh=lh,  # Will be ignored by bicycle model
            lf1=lf1,
            lr=lr,
            lf2=lf2,  # Will be ignored by bicycle model
            lr2=lr2,  # Will be ignored by bicycle model
            tractor_width=tractor_width,
            trailer_width=trailer_width,  # Will be ignored by bicycle model
            v_max=v_max,
            delta_max_deg=delta_max_deg,
            d_thr_factor=d_thr_factor,
            k_switch=k_switch,
            steering_weight=steering_weight,
            preference_penalty_weight=preference_penalty_weight,
            heading_reward_weight=heading_reward_weight,
            terminal_reward_threshold=terminal_reward_threshold,
            terminal_reward_weight=terminal_reward_weight,
            ref_pos_weight=ref_pos_weight,
            ref_theta1_weight=ref_theta1_weight,
            ref_theta2_weight=ref_theta2_weight,  # Will be ignored by bicycle model
            **perturbation_kwargs,
        )
    else:
        raise ValueError(f"Unknown environment: {env_name}")
